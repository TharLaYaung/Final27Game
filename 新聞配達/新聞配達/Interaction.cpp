#include "Interaction.h"



// コンストラクタ

Interaction::Interaction()
{
    // 最初は何も調べられない
    canInteract = false;

    // 最初はEキーを押していない
    oldEKey = false;

    // メッセージ表示時間を0にする
    messageTimer = 0;
}

// インタラクト処理
void Interaction::Update(Player& player)
{

    // プレイヤーの位置を取得する
    VECTOR playerPosition =
        player.GetPosition();


    // ========================================
    // プレイヤーが向いている方向を取得する
    // ========================================
    VECTOR forward =
        player.GetForward();


    // ========================================
    // プレイヤーの目の位置
    // ========================================
    VECTOR rayStart =
        playerPosition;


    // ========================================
    // プレイヤーの前方3メートルの位置を作る
    // ========================================
    VECTOR rayEnd;

    rayEnd.x =
        rayStart.x + forward.x * 3.0f;

    rayEnd.y =
        rayStart.y + forward.y * 3.0f;

    rayEnd.z =
        rayStart.z + forward.z * 3.0f;


    // ========================================
    // 今回はモデルを使わないので
    // 赤い箱をインタラクト対象として使用する
    // ========================================

    // 赤い箱の中心位置
    VECTOR boxPosition =
        VGet(
            0.0f,
            1.0f,
            6.0f
        );


    // ========================================
    // プレイヤーと箱の距離を計算する
    // ========================================

    float distance =
        VSize(
            VSub(
                boxPosition,
                playerPosition
            )
        );


    // ========================================
    // プレイヤーが箱から
    // 3メートル以内にいるか確認する
    // ========================================
    if (distance <= 3.0f)
    {
        // インタラクト可能
        canInteract = true;
    }
    else
    {
        // 遠いのでインタラクトできない
        canInteract = false;
    }


    // ========================================
    // 現在Eキーが押されているか
    // ========================================
    bool currentEKey =
        CheckHitKey(KEY_INPUT_E) != 0;


    // ========================================
    // インタラクト可能な状態で
    // Eキーを「今押した瞬間」だけ処理する
    // ========================================
    if (
        canInteract == true &&
        currentEKey == true &&
        oldEKey == false
        )
    {
        // 「調べました」を
        // 約120フレーム表示する
        messageTimer = 120;
    }


    // ========================================
    // 前フレームのEキー状態を保存する
    // ========================================
    oldEKey = currentEKey;


    // ========================================
    // メッセージ表示時間を減らす
    // ========================================
    if (messageTimer > 0)
    {
        messageTimer--;
    }
}


// ========================================
// インタラクトUIを描画する
// ========================================
void Interaction::Draw()
{
    // ========================================
    // インタラクトできる場合
    // ========================================
    if (canInteract == true)
    {
        // 「E：調べる」を表示する
        DrawString(
            570,
            500,
            "E : Interact",
            GetColor(
                255,
                255,
                255
            )
        );
    }


    // ========================================
    // Eキーを押した後
    // ========================================
    if (messageTimer > 0)
    {
        // テストメッセージを表示する
        DrawString(
            570,
            550,
            "Interaction!",
            GetColor(
                255,
                255,
                0
            )
        );
    }
}