// Ground.hを読み込む
#include "Ground.h"


// ========================================
// 地面を描画する関数
// ========================================
void DrawGround()
{
    // 地面の色を作る
    // RGB = 100,100,100
    unsigned int groundColor =
        GetColor(
            100,
            100,
            100
        );


    // ========================================
    // 地面の4つの角を作る
    // ========================================

    // 左奥
    VECTOR p1 =
        VGet(
            -200.0f,
            0.0f,
            -200.0f
        );

    // 右奥
    VECTOR p2 =
        VGet(
            200.0f,
            0.0f,
            -200.0f
        );

    // 左手前
    VECTOR p3 =
        VGet(
            -200.0f,
            0.0f,
            200.0f
        );

    // 右手前
    VECTOR p4 =
        VGet(
            200.0f,
            0.0f,
            200.0f
        );


    // ========================================
    // 三角形1枚目を描画
    // ========================================

    DrawTriangle3D(
        p1,
        p2,
        p3,
        groundColor,
        TRUE
    );


    // ========================================
    // 三角形2枚目を描画
    // ========================================

    DrawTriangle3D(
        p2,
        p4,
        p3,
        groundColor,
        TRUE
    );
}